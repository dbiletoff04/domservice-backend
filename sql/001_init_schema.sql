-- Схема базы данных сервиса «Домсервис» (по модели данных Р1 и диаграмме Р8)

CREATE TABLE IF NOT EXISTS user_role (
    role_code   VARCHAR(32) PRIMARY KEY,
    name        VARCHAR(64) NOT NULL,
    description TEXT        NOT NULL
);

CREATE TABLE IF NOT EXISTS request_status (
    status_code VARCHAR(32) PRIMARY KEY,
    name        VARCHAR(64) NOT NULL,
    description TEXT        NOT NULL
);

CREATE TABLE IF NOT EXISTS management_company (
    company_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(128) NOT NULL UNIQUE,
    contact_phone VARCHAR(20),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS problem_category (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(64) NOT NULL UNIQUE,
    is_active   BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS app_user (
    user_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone      VARCHAR(20)  NOT NULL UNIQUE,
    full_name  VARCHAR(128),
    role_code  VARCHAR(32)  NOT NULL REFERENCES user_role(role_code) ON UPDATE CASCADE ON DELETE RESTRICT,
    company_id INTEGER               REFERENCES management_company(company_id) ON UPDATE CASCADE ON DELETE SET NULL,
    consent_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS request (
    request_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_number         VARCHAR(16)   NOT NULL UNIQUE,
    submission_key         UUID,
    submission_fingerprint VARCHAR(64),
    resident_id            INTEGER       NOT NULL REFERENCES app_user(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    company_id             INTEGER       NOT NULL REFERENCES management_company(company_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    category_id            INTEGER       NOT NULL REFERENCES problem_category(category_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    address                VARCHAR(255)  NOT NULL,
    apartment              VARCHAR(16)   NOT NULL,
    description            VARCHAR(1000) NOT NULL,
    status_code            VARCHAR(32)   NOT NULL DEFAULT 'accepted' REFERENCES request_status(status_code) ON UPDATE CASCADE ON DELETE RESTRICT,
    master_id              INTEGER                REFERENCES app_user(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    deadline_at            TIMESTAMPTZ,
    created_at             TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    updated_at             TIMESTAMPTZ   NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS request_status_history (
    history_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id       INTEGER      NOT NULL REFERENCES request(request_id) ON UPDATE CASCADE ON DELETE CASCADE,
    from_status_code VARCHAR(32)           REFERENCES request_status(status_code) ON UPDATE CASCADE ON DELETE RESTRICT,
    to_status_code   VARCHAR(32)  NOT NULL REFERENCES request_status(status_code) ON UPDATE CASCADE ON DELETE RESTRICT,
    actor_id         INTEGER      NOT NULL REFERENCES app_user(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    comment          VARCHAR(500),
    changed_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS notification (
    notification_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id      INTEGER      NOT NULL REFERENCES request(request_id) ON UPDATE CASCADE ON DELETE CASCADE,
    recipient_id    INTEGER      NOT NULL REFERENCES app_user(user_id) ON UPDATE CASCADE ON DELETE CASCADE,
    status_code     VARCHAR(32)  NOT NULL REFERENCES request_status(status_code) ON UPDATE CASCADE ON DELETE RESTRICT,
    message_text    VARCHAR(500) NOT NULL,
    state           VARCHAR(16)  NOT NULL DEFAULT 'new',
    attempts        INTEGER      NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    sent_at         TIMESTAMPTZ,
    CONSTRAINT chk_notification_state CHECK (state IN ('new', 'sent', 'error')),
    CONSTRAINT chk_notification_attempts CHECK (attempts >= 0)
);

-- Индексы для ускорения поиска и защиты от дублей при повторе отправки
CREATE INDEX IF NOT EXISTS ix_app_user_role_code ON app_user(role_code);
CREATE INDEX IF NOT EXISTS ix_app_user_company_id ON app_user(company_id);

CREATE INDEX IF NOT EXISTS ix_request_status_code ON request(status_code);
CREATE INDEX IF NOT EXISTS ix_request_resident_id ON request(resident_id);
CREATE INDEX IF NOT EXISTS ix_request_master_id ON request(master_id);
CREATE INDEX IF NOT EXISTS ix_request_company_status ON request(company_id, status_code);
CREATE INDEX IF NOT EXISTS ix_request_created_at ON request(created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS uq_request_resident_submission_key
    ON request(resident_id, submission_key)
    WHERE submission_key IS NOT NULL;

CREATE INDEX IF NOT EXISTS ix_history_request_changed ON request_status_history(request_id, changed_at);

CREATE INDEX IF NOT EXISTS ix_notification_state_created ON notification(state, created_at);
CREATE INDEX IF NOT EXISTS ix_notification_recipient_created ON notification(recipient_id, created_at DESC);